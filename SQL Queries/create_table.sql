CREATE TABLE IF NOT EXISTS raw_data ( 
	Record_ID VARCHAR(8), 
    Year INT,
    Country VARCHAR(255),
    Industry VARCHAR(255),
    Company_Size VARCHAR(255),
    Job_Role VARCHAR(255),
    Age_Group VARCHAR(5),
    AI_Agent_Usage VARCHAR(255),
    AI_Agent_Type VARCHAR(255),
    Task_Automated INT,
    Hours_Saved_Per_Week FLOAT(10),
    Productivity_Change_Percent FLOAT(10),
    AI_Skill_Level VARCHAR(255),
    Training_Hours INT,
    Monthly_AI_Cost FLOAT(10),
    Job_Satisfaction INT,
    Workload_Level VARCHAR(255),
    Trust_in_AI INT,
    Human_AI_Collaboration VARCHAR(255),
    Error_Rate FLOAT(10),
    Job_Risk_Level VARCHAR(255),
    Overall_AI_Impact VARCHAR(255)
);